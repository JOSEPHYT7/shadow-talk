export function detectSocialPlatform(input) {
  if (!input || typeof input !== 'string') return 'website';
  const lower = input.toLowerCase().trim();

  if (/instagram\.com|instagr\.am|^@?[\w._]+(?=.*ig)/i.test(lower) || lower.includes('instagram')) {
    return 'instagram';
  }
  if (/twitter\.com|x\.com|^@?[\w_]+(?=.*(twitter|x\.com))/i.test(lower) || lower.includes('twitter') || lower.includes('x.com')) {
    return 'twitter';
  }
  if (/github\.com|^github\.com/i.test(lower) || lower.includes('github')) {
    return 'github';
  }
  if (/linkedin\.com/i.test(lower) || lower.includes('linkedin')) {
    return 'linkedin';
  }
  if (/youtube\.com|youtu\.be/i.test(lower) || lower.includes('youtube')) {
    return 'youtube';
  }
  if (/t\.me|telegram\.me/i.test(lower) || lower.includes('telegram')) {
    return 'telegram';
  }
  if (/discord\.gg|discord\.com/i.test(lower) || lower.includes('discord')) {
    return 'discord';
  }
  if (/reddit\.com/i.test(lower) || lower.includes('reddit')) {
    return 'reddit';
  }
  return 'website';
}

